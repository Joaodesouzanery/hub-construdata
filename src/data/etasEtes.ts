/** Convert stations to GeoJSON FeatureCollection */
export function estacoesToGeoJSON(): GeoJSON.FeatureCollection {
  return {
    type: "FeatureCollection",
    features: estacoesTratamento.map((e) => ({
      type: "Feature" as const,
      properties: {
        id: e.id,
        nome: e.nome,
        tipo: e.tipo,
        operadora: e.operadora,
        estado: e.estado,
        municipio: e.municipio,
        capacidade_ls: e.capacidade_ls,
        populacao_atendida: e.populacao_atendida,
        status: e.status,
      },
      geometry: {
        type: "Point" as const,
        coordinates: [e.lng, e.lat],
      },
    })),
  };
}
