/** Convert ANA stations to GeoJSON FeatureCollection */
export function estacoesANAToGeoJSON(): GeoJSON.FeatureCollection {
  return {
    type: "FeatureCollection",
    features: estacoesANA.map((e) => ({
      type: "Feature" as const,
      properties: {
        id: e.id,
        codigo: e.codigo,
        nome: e.nome,
        tipo: e.tipo,
        rio: e.rio,
        bacia: e.bacia,
        estado: e.estado,
        municipio: e.municipio,
        nivel_atual_m: e.nivel_atual_m,
        vazao_atual_m3s: e.vazao_atual_m3s,
        chuva_acum_24h_mm: e.chuva_acum_24h_mm,
        status: e.status,
        cor: statusCores[e.status],
      },
      geometry: {
        type: "Point" as const,
        coordinates: [e.lng, e.lat],
      },
    })),
  };
}
